const supportedLanguages = ["en", "si"];
const dictionaries = { en: english, si: sinhala };
const englishKeys = new Map(
  Object.entries(english).map(([key, value]) => [value, key]),
);
const registeredTextNodes = new Map();
const registeredAttributes = new Map();
let currentLanguage = "en";
let initialized = false;
let languageToggle;

function getStoredLanguage() {
  try {
    const savedLanguage = window.localStorage.getItem("lingolift-language");
    return supportedLanguages.includes(savedLanguage) ? savedLanguage : "en";
  } catch {
    return "en";
  }
}

function saveLanguage(language) {
  try {
    window.localStorage.setItem("lingolift-language", language);
  } catch {
    // Language changes still work for this page when storage is unavailable.
  }
}

function translateValue(key, language = currentLanguage) {
  return dictionaries[language][key] ?? english[key];
}

function isKnownTranslation(value, key, index, original) {
  const knownValues = [original];
  [english[key], sinhala[key]].forEach((translation) => {
    const part = Array.isArray(translation) ? translation[index] : translation;
    if (typeof part === "string") knownValues.push(part);
  });
  return knownValues.includes(value.trim());
}

function preserveWhitespace(original, translated) {
  const leading = original.match(/^\s*/)?.[0] ?? "";
  const trailing = original.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

function shouldSkipTextNode(node) {
  const parent = node.parentElement;
  return !parent || Boolean(parent.closest(
    "script, style, noscript, textarea, [contenteditable='true'], [aria-live], [role='status'], [data-profile-email], [data-i18n-ignore]",
  ));
}

function addTextNode(node, key, original = node.nodeValue, index = 0, count = 1) {
  const existing = registeredTextNodes.get(node);
  if (!existing || existing.key !== key) {
    registeredTextNodes.set(node, { key, original, index, count });
  }
}

function addAttribute(element, attribute, key, original = element.getAttribute(attribute)) {
  let attributes = registeredAttributes.get(element);
  if (!attributes) {
    attributes = new Map();
    registeredAttributes.set(element, attributes);
  }
  const existing = attributes.get(attribute);
  if (!existing || existing.key !== key) attributes.set(attribute, { key, original });
}

function registerExplicitTranslations(root = document) {
  const elements = [];
  if (root instanceof Element && root.matches("[data-i18n]")) elements.push(root);
  elements.push(...root.querySelectorAll("[data-i18n]"));

  elements.forEach((element) => {
    const key = element.dataset.i18n;
    if (!key || !Object.hasOwn(english, key)) return;

    const attributes = (element.dataset.i18nAttr || "").split(",").filter(Boolean);
    attributes.forEach((attribute) => {
      if (element.hasAttribute(attribute)) addAttribute(element, attribute, key);
    });

    if (element.dataset.i18nText === "false") return;
    const walker = document.createTreeWalker(element, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    let node = walker.nextNode();
    while (node) {
      if (!shouldSkipTextNode(node) && node.nodeValue.trim()) textNodes.push(node);
      node = walker.nextNode();
    }
    textNodes.forEach((textNode, index) => {
      addTextNode(textNode, key, textNode.nodeValue, index, textNodes.length);
    });
  });
}

function registerExistingStaticText() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    if (!shouldSkipTextNode(node)) {
      const key = englishKeys.get(node.nodeValue.trim());
      if (key) addTextNode(node, key);
    }
    node = walker.nextNode();
  }

  document.querySelectorAll("[placeholder], [title], [aria-label], [alt]").forEach((element) => {
    if (element.closest("[data-i18n-ignore]")) return;
    ["placeholder", "title", "aria-label", "alt"].forEach((attribute) => {
      const value = element.getAttribute(attribute);
      const key = value && englishKeys.get(value.trim());
      if (key) addAttribute(element, attribute, key);
    });
  });

  const titleKey = englishKeys.get(document.title.trim());
  if (titleKey) document.documentElement.dataset.i18nTitle = titleKey;
}

function applyTranslations() {
  registeredTextNodes.forEach(({ key, original, index, count }, node) => {
    if (!node.isConnected) return;
    if (!isKnownTranslation(node.nodeValue, key, index, original)) return;
    const translated = translateValue(key);
    const translatedText = Array.isArray(translated)
      ? translated[index]
      : count === 1 ? translated : original;
    node.nodeValue = preserveWhitespace(original, translatedText ?? original);
  });

  registeredAttributes.forEach((attributes, element) => {
    if (!element.isConnected) return;
    attributes.forEach(({ key, original }, attribute) => {
      if (!isKnownTranslation(element.getAttribute(attribute) || "", key, 0, original)) return;
      element.setAttribute(attribute, translateValue(key) ?? original);
    });
  });

  const titleKey = document.documentElement.dataset.i18nTitle;
  if (titleKey) document.title = translateValue(titleKey);
  document.documentElement.lang = currentLanguage;

  if (languageToggle) {
    languageToggle.textContent = currentLanguage === "en" ? "සිං" : "ENG";
    languageToggle.setAttribute(
      "aria-label",
      translateValue(currentLanguage === "en" ? "language.switch-to-sinhala" : "language.switch-to-english"),
    );
    languageToggle.setAttribute("aria-pressed", String(currentLanguage === "si"));
  }
}

function setLanguage(language) {
  if (!supportedLanguages.includes(language)) {
    throw new RangeError(`Unsupported language: ${language}`);
  }

  currentLanguage = language;
  saveLanguage(language);
  applyTranslations();
  return currentLanguage;
}

function registerTranslations(language, entries) {
  if (!supportedLanguages.includes(language)) {
    throw new RangeError(`Unsupported language: ${language}`);
  }
  if (!entries || typeof entries !== "object" || Array.isArray(entries)) {
    throw new TypeError("Translations must be provided as a key-value object.");
  }
  Object.entries(entries).forEach(([key, value]) => {
    if (!key || !(typeof value === "string" || (Array.isArray(value) && value.every((part) => typeof part === "string")))) {
      throw new TypeError(`Translation "${key}" must be a string or an array of strings.`);
    }
    if (language === "si" && !Object.hasOwn(english, key)) {
      throw new RangeError(`Missing English fallback for translation key: ${key}`);
    }
  });

  Object.assign(dictionaries[language], entries);
  if (language === "en") {
    Object.entries(entries).forEach(([key, value]) => {
      if (typeof value === "string") englishKeys.set(value, key);
    });
  }
  if (language === currentLanguage) applyTranslations();
}

function registerElement(element, key, options = {}) {
  if (!(element instanceof Element)) {
    throw new TypeError("A translatable DOM element is required.");
  }
  if (typeof key !== "string" || !key) {
    throw new TypeError("A non-empty translation key is required.");
  }
  if (!Object.hasOwn(english, key)) {
    throw new RangeError(`Missing English fallback for translation key: ${key}`);
  }

  element.dataset.i18n = key;
  const attributes = options.attribute
    ? Array.isArray(options.attribute) ? options.attribute : [options.attribute]
    : [];
  if (attributes.length) {
    element.dataset.i18nAttr = attributes.join(",");
  } else {
    delete element.dataset.i18nAttr;
  }
  if (options.text === false || (attributes.length && options.text !== true)) {
    element.dataset.i18nText = "false";
  } else {
    delete element.dataset.i18nText;
  }
  registerExplicitTranslations(element);
  applyTranslations();
}

function refreshTranslations(root = document) {
  registerExplicitTranslations(root);
  applyTranslations();
}

function addLanguageToggle() {
  const target = document.querySelector(".primary-nav") || document.querySelector(".auth-header");
  if (!target) return;

  languageToggle = target.querySelector("[data-language-toggle]");
  if (!languageToggle) {
    languageToggle = document.createElement("button");
    languageToggle.type = "button";
    languageToggle.className = "nav-cta language-toggle";
    languageToggle.dataset.languageToggle = "";
    const appLink = target.querySelector('a.nav-cta[href="download.html"]');
    if (appLink) {
      appLink.before(languageToggle);
    } else {
      target.append(languageToggle);
    }
  }
  languageToggle.addEventListener("click", () => {
    setLanguage(currentLanguage === "en" ? "si" : "en");
  });
}

function initializeTranslations() {
  if (initialized) return;
  initialized = true;
  currentLanguage = getStoredLanguage();
  registerExistingStaticText();
  registerExplicitTranslations();
  addLanguageToggle();
  applyTranslations();
}

window.LingoliftI18n = Object.freeze({
  getLanguage: () => currentLanguage,
  translate: translateValue,
  setLanguage,
  registerTranslations,
  registerElement,
  refresh: refreshTranslations,
});

initializeTranslations();
